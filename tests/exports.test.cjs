const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '..');
test('JSON backup and QYL exports preserve special characters and custom wrong answers', async () => {
  const dom = new JSDOM(fs.readFileSync(path.join(root, 'index.html'), 'utf8'), { url: 'https://export-test.example/', runScripts: 'outside-only' });
  const w = dom.window;
  w.scrollTo = () => {};
  const downloads = [];
  w.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  w.HTMLDialogElement.prototype.close = function () { this.open = false; };
  w.HTMLAnchorElement.prototype.click = function () {};
  w.URL.createObjectURL = blob => { downloads.push(blob); return 'blob:test'; };
  w.URL.revokeObjectURL = () => {};
  const data = { version: 1, quizzes: [{ id: 'export', name: 'M\u00fcnchen & capitals', description: '', cards: [{ id: 'c', question: 'A & B < C', answer: 'x ]]> y', notes: 'Note & \"quotes\"', wrongAnswers: ['Wrong < one', 'Wrong & two'] }] }], settings: { count: 20 }, history: [] };
  w.localStorage.setItem('quiz-your-lizard:v1', JSON.stringify(data));
  for (const file of ['vendor/lucide.min.js', 'seed.js', 'core.js', 'app.js']) w.eval(fs.readFileSync(path.join(root, file), 'utf8'));
  const click = selector => w.document.querySelector(selector).click();
  const contents = blob => new Promise((resolve, reject) => { const reader = new w.FileReader(); reader.onload = () => resolve(reader.result); reader.onerror = reject; reader.readAsText(blob); });
  click('[data-action="backup"]');
  const backup = JSON.parse(await contents(downloads.pop()));
  assert.deepEqual(backup.quizzes, data.quizzes);
  click('[data-action="open-quiz"]'); click('[data-action="export-quiz"]'); click('[data-action="export-qyl"]');
  const xml = new w.DOMParser().parseFromString(await contents(downloads.pop()), 'application/xml');
  assert.equal(xml.querySelector('parsererror'), null);
  assert.equal(xml.documentElement.getAttribute('name'), data.quizzes[0].name);
  assert.equal(xml.querySelector('Word1').textContent, 'A & B < C');
  assert.equal(xml.querySelector('Word2').textContent, 'x ]]> y');
  assert.equal(xml.querySelector('Note').textContent, 'Note & "quotes"');
  assert.equal(xml.querySelector('Word3').textContent, 'Wrong < one');
  assert.equal(xml.querySelector('Word4').textContent, 'Wrong & two');
  dom.window.close();
});
